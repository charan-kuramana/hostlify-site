export type IconName = keyof typeof icons;

/** Reverse lookup (component → registry name), e.g. for nav items that hold a Lucide component. */
export function iconNameOf(cmp: LucideIcon): string {
  for (const [name, c] of Object.entries(icons)) if (c === cmp) return name;
  return "";
}

export function Icon({ name, ...props }: LucideProps & { name: string }) {
  const Cmp = (icons as Record<string, LucideIcon>)[name] ?? CircleCheck;
  return <Cmp strokeWidth={1.75} aria-hidden="true" {...props} />;
}
